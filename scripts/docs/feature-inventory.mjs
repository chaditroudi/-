#!/usr/bin/env node
// Feature-parity inventory: what each screen file offers (labels, buttons, tabs, dialogs, server calls).
// Run before and after a redesign and diff the JSON: anything that disappears must be explained.
//   node scripts/docs/feature-inventory.mjs --json > docs/evidence/tablet-first-ui/inventory-<stage>.json
//   node scripts/docs/feature-inventory.mjs           > docs/plans/TABLET_FIRST_FEATURE_PARITY.generated.md
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("../../", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const SKIP = new Set(["ui"]);
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) { if (!SKIP.has(name)) walk(path); continue; }
    if (name.endsWith(".tsx") && !name.includes(".test.")) files.push(path);
  }
};
walk(join(root, "src/components"));
walk(join(root, "src/pages"));

const text = (s) => s.replace(/\{[^}]*\}/g, "…").replace(/\s+/g, " ").trim();
const collect = (src, re, group = 1) => {
  const found = new Set();
  for (const m of src.matchAll(re)) { const v = text(m[group] ?? ""); if (v && v !== "…" && v.length < 90) found.add(v); }
  return [...found].sort();
};
const T_KEY = /\bt\(\s*['"]([\w.-]+)['"]/g;

const inventory = files.sort().map((path) => {
  const src = readFileSync(path, "utf8");
  return {
    file: relative(root, path).split(sep).join("/"),
    lines: src.split("\n").length,
    labels: collect(src, /<(?:Label|FormLabel)\b(?:=>|[^>])*>([^<]+)</g),
    buttons: collect(src, /<Button\b(?:=>|[^>])*>\s*(?:<[A-Z]\w*[^>]*\/>\s*)?([^<{][^<]*)</g),
    tabs: collect(src, /<TabsTrigger\b(?:=>|[^>])*>\s*(?:<[A-Z]\w*[^>]*\/>\s*)?([^<]+)</g),
    dialogs: collect(src, /<(?:DialogTitle|SheetTitle|AlertDialogTitle)\b(?:=>|[^>])*>([^<]+)</g),
    placeholders: collect(src, /placeholder="([^"]+)"/g),
    serverCalls: [...new Set([...src.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"]@\/(?:hooks|store\/api)\/[^'"]+['"]/g)].flatMap((m) => m[1].split(",").map((x) => x.trim().replace(/^type\s+/, "")).filter((x) => /^use[A-Z]/.test(x))))].sort(),
    translationKeys: [...new Set([...src.matchAll(T_KEY)].map((m) => m[1]))].length,
  };
});

if (process.argv.includes("--json")) {
  console.log(JSON.stringify(inventory, null, 1));
} else {
  const total = (k) => inventory.reduce((n, f) => n + f[k].length, 0);
  const out = [
    "# Feature inventory (generated)",
    "",
    "Generated by `node scripts/docs/feature-inventory.mjs`. Do not edit by hand; rerun it.",
    `Files: ${inventory.length}. Labels ${total("labels")}, buttons ${total("buttons")}, tabs ${total("tabs")}, dialogs ${total("dialogs")}, server hooks ${total("serverCalls")}.`,
    "Text inside `{…}` expressions and icon-only buttons are not captured; the hand-checked parity notes cover those.",
    "",
  ];
  let folder = "";
  for (const f of inventory) {
    const dir = f.file.split("/").slice(0, -1).join("/");
    if (dir !== folder) { folder = dir; out.push(`## ${dir}`, ""); }
    const parts = [
      ["Labels", f.labels], ["Buttons", f.buttons], ["Tabs", f.tabs], ["Dialogs", f.dialogs],
      ["Placeholders", f.placeholders], ["Server hooks", f.serverCalls],
    ].filter(([, v]) => v.length);
    if (!parts.length && !f.translationKeys) continue;
    out.push(`### ${f.file.split("/").pop()} (${f.lines} lines, ${f.translationKeys} translation keys)`);
    for (const [name, values] of parts) out.push(`- **${name}:** ${values.join(" · ")}`);
    out.push("");
  }
  console.log(out.join("\n"));
}
